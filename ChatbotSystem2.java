import java.util.*;

class Document {
    String title; int version;
    Document(String title, int version) { this.title = title; this.version = version; }
    void indexDocument() { System.out.println("Indexing: " + title + " v" + version); }
}

class Response {
    String answerText, sourceCitation;
    Response(String answerText, String sourceCitation) {
        this.answerText = answerText; this.sourceCitation = sourceCitation;
    }
    void displayAnswer() { System.out.println("Answer: " + answerText + " | Source: " + sourceCitation); }
}

class Query {
    String queryText; float confidenceScore;
    Query(String queryText) { this.queryText = queryText; }
    void preprocess() { queryText = queryText.trim().toLowerCase(); }
    void getEmbedding() { System.out.println("Embedding generated for: " + queryText); }
}

class ChatbotEngine {
    String modelName;
    List<Document> documents = new ArrayList<>();
    ChatbotEngine(String modelName) { this.modelName = modelName; }

    void addDocument(Document d) { documents.add(d); }

    void retrievePassages(Query q) {
        System.out.println("Retrieving passages for: " + q.queryText);
    }

    Response generateAnswer(Query q) {
        q.preprocess(); q.getEmbedding(); retrievePassages(q);
        q.confidenceScore = 0.87f;
        String source = documents.isEmpty() ? "No source" : documents.get(0).title;
        return new Response("Generated by " + modelName, source);
    }
}

class Student {
    String name;
    Student(String name) { this.name = name; }

    Response askQuery(ChatbotEngine engine, String text) {
        System.out.println("\n" + name + " asked: " + text);
        return engine.generateAnswer(new Query(text));
    }

    void giveFeedback(String feedback) { System.out.println(name + " feedback: " + feedback); }
}

class Admin {
    String name;
    Admin(String name) { this.name = name; }

    void uploadDocument(ChatbotEngine engine, Document d) {
        d.indexDocument(); engine.addDocument(d);
        System.out.println(name + " uploaded: " + d.title);
    }

    void viewAnalytics() { System.out.println(name + " viewing analytics dashboard"); }
}

public class ChatbotSystem2 {
    public static void main(String[] args) {
        ChatbotEngine engine = new ChatbotEngine("CollegeRAG-v1");

        Admin admin = new Admin("Admin User");
        admin.uploadDocument(engine, new Document("Admission Process Guide", 1));
        admin.viewAnalytics();

        Student student = new Student("Anushka");
        Response response = student.askQuery(engine, "When does the admission process start?");
        response.displayAnswer();
        student.giveFeedback("Helpful answer, thumbs up");
    }
}
